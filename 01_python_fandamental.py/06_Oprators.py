#Types of Operators
# 01_Arithmetic Operators: 
# 1. + (Addition), - (Subtraction), * (Multiplication), / (Division), %(Modulus), ** (Exponentiation), // (Floor Division).


# Example:
print(43+45)
print(34*334)
print(567**3)
print(34-12)
print(234/2)
print(234//2)
print(234%2)




# 02_Comparison opratorTypes of Operators
#== (Equal), != (Not Equal), > (Greater Than), < (Less Than), >=(Greater Than or Equal), <= (Less Than or Equal).

# Example
print(10>9.4)
print(100==5)
print(100!=100)
print(100<23)
print(100<=101)
print(100>=100)

# 03_Logical Oprator
# and, or, not
#Example
print(True and False)
print(False and True)
print(True or False)
print(not True)

# 04_Assinment oprator
# =,+=, *=, /=, %=, **=, //= .
x = 10
x += 6 # Equivalent to x = x+6
print(x) # output:16



# 05_Membership operator
# in, not in.
# Example
fruits = ["apple","banana","cherry","grapes","pomeogranet","watermelon"]
